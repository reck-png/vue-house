   FG 點擊隱藏
========================= */

const fgVisible = ref(true);

let fgTimer = null;

const handleFgInteraction = () => {

  // 立即隱藏
  fgVisible.value = false;

  // 重新計時
  clearTimeout(fgTimer);

  fgTimer = setTimeout(() => {
    fgVisible.value = true;
  }, 1000);
};

